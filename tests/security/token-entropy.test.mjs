import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import crypto from 'crypto';

function generateSecureToken() {
  return crypto.randomBytes(32).toString('hex');
}

describe('Security: Token Entropy & Unpredictability', () => {
  it('generates 256-bit (64 hex char) cryptographically random tokens', () => {
    const token = generateSecureToken();
    assert.equal(token.length, 64);
    assert.match(token, /^[0-9a-f]{64}$/);
  });

  it('guarantees zero collisions across large batch token generation', () => {
    const seen = new Set();
    const count = 1000;

    for (let i = 0; i < count; i++) {
      const token = generateSecureToken();
      assert.equal(seen.has(token), false, `Collision detected at index ${i}`);
      seen.add(token);
    }

    assert.equal(seen.size, count);
  });

  it('proves high entropy distribution across generated bytes', () => {
    const token = generateSecureToken();
    // A 64-character hex string from CSPRNG should contain diverse characters
    const uniqueChars = new Set(token.split(''));
    // With 16 hex chars and 64 positions, we expect at least 10 distinct hex digits
    assert.ok(uniqueChars.size >= 10, `Expected diverse character set, got ${uniqueChars.size}`);
  });
});

